import AppKit

/// Watches the Mac clipboard (macOS has no change notification, so it polls the change count)
/// and writes text that arrives from the phone without echoing it back.
@MainActor
final class ClipboardSync {
    var onChange: ((String) -> Void)?
    /// A copied image, written to a temporary PNG (only images copied on this Mac).
    var onImage: ((URL) -> Void)?
    /// When the clipboard last changed, in milliseconds since 1970 (for `clipboard.connect`).
    private(set) var lastChange: Int64 = 0

    private let pasteboard = NSPasteboard.general
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Password managers mark secrets with these types; never send those to a phone.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    var currentText: String? {
        guard !isPrivate else { return nil }
        return pasteboard.string(forType: .string).flatMap { $0.isEmpty ? nil : $0 }
    }

    private var isPrivate: Bool {
        let types = pasteboard.types ?? []
        return Self.privateTypes.contains(where: types.contains)
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { _ in
            MainActor.assumeIsolated { self.poll() }
        }
    }

    func setFromPhone(_ text: String) {
        guard text != pasteboard.string(forType: .string) else { return }
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        changeCount = pasteboard.changeCount
        lastChange = Int64(Date().timeIntervalSince1970 * 1000)
    }

    /// Puts an image from the phone on the clipboard, as image data only (no file is saved).
    func setImageFromPhone(_ image: NSImage, file: URL) {
        let item = NSPasteboardItem()
        if let tiff = image.tiffRepresentation {
            item.setData(tiff, forType: .tiff)
            if let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                item.setData(png, forType: .png)
            }
        }
        if file.pathExtension.lowercased().hasPrefix("jp"), let jpeg = try? Data(contentsOf: file) {
            item.setData(jpeg, forType: NSPasteboard.PasteboardType("public.jpeg"))
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        changeCount = pasteboard.changeCount
        lastChange = Int64(Date().timeIntervalSince1970 * 1000)
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        lastChange = Int64(Date().timeIntervalSince1970 * 1000)
        if let text = currentText {
            onChange?(text)
        } else if !isPrivate, let file = copiedImageFile() {
            onImage?(file)
        }
    }

    /// Whatever image is on the clipboard (image data, or a copied image file), as a file to send.
    func imageForSending() -> URL? {
        if let file = copiedImageFile(allowFileURL: true) { return file }
        guard let url = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])?.first as? URL,
              NSImage(contentsOf: url) != nil
        else { return nil }
        return url
    }

    /// Copied image data (not a copied file) as a PNG in the temporary folder.
    private func copiedImageFile(allowFileURL: Bool = false) -> URL? {
        let types = pasteboard.types ?? []
        guard allowFileURL || !types.contains(.fileURL), types.contains(.png) || types.contains(.tiff),
              let data = pasteboard.data(forType: .png)
                ?? pasteboard.data(forType: .tiff).flatMap({ NSBitmapImageRep(data: $0)?.representation(using: .png, properties: [:]) })
        else { return nil }
        let stamp = Date().formatted(.iso8601.year().month().day().time(includingFractionalSeconds: false)).replacingOccurrences(of: ":", with: ".")
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("Copied Image \(stamp).png")
        return (try? data.write(to: url)) != nil ? url : nil
    }
}
